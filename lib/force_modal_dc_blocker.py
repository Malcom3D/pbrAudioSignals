"""
DC / envelope-shaped bias removal for MODAL_DISPLACEMENT tracks.

A modal synthesis output (RigidBodySynth, ResonanceSynth, ProxySynth)
contains a slowly-varying bias component generated by the per-mode
``g[i] = gain[i] * (1 - r[i]) * s[i]`` coefficient in ModalBank. When the
excitation is asymmetric (e.g. one-sided impacts), the DC offset that
accumulates through the leaky integrator is proportional to the *total*
integrated force. That is exactly what ``ForceDataSequence`` gives us.

This processor removes that bias while preserving real transients:

  1. Densify the force envelope to per-sample resolution.
  2. Compute the *expected DC trajectory* by low-passing the force envelope
     with a time constant matched to the modal model's mean T60 (so that
     the DC we remove matches the time-scale of the resonator).
  3. Subtract that expectation, scaled by a per-channel attenuation
     that is a smooth function of the force envelope.
"""

import numpy as np
import numba as nb

from ..core.processor import BaseProcessor, register_processor
from ..core.groups import MODAL_DISPLACEMENT
from .force_sidechannel import get_force_sequence, sample_envelope

@nb.njit(cache=True, nogil=True, fastmath=True, parallel=True)
def _leaky_integrate_1d(f: np.ndarray, tau_samples: np.float32) -> np.ndarray:
    """
    y[n] = y[n-1] * exp(-1/tau) + f[n] * (1 - exp(-1/tau))
    """
    n = f.shape[0]
    out = np.empty(n, dtype=np.float32)
    a = np.exp(-np.float32(1.0) / np.float32(tau_samples))
    b = np.float32(1.0) - a
    y = np.float32(0.0)
    for i in range(n):
        y = a * y + b * f[i]
        out[i] = y
    return out


@nb.njit(cache=True, nogil=True, fastmath=True, parallel=True)
def _modal_dc_block_2d(x: np.ndarray, dc_expect: np.ndarray, alpha_quiet: np.float32, alpha_active: np.float32) -> np.ndarray:
    """
    Per-sample DC-blocker whose pole and removal weight move with the
    modal DC expectation.

      - ``dc_expect`` is the leaky-integrated force (per-sample, range ~[0,1]).
      - ``alpha_quiet``: pole used where dc_expect approaches 0.
      - ``alpha_active``: pole used where dc_expect is max.
    """
    C, S = x.shape
    out = np.empty_like(x)
    mx = np.float32(1e-12)
    for i in range(S):
        if dc_expect[i] > mx:
            mx = dc_expect[i]

    inv_mx = np.float32(1.0) / mx
    for ch in nb.prange(C):
        xp = np.float32(0.0)
        yp = np.float32(0.0)
        for i in range(S):
            f = dc_expect[i] * inv_mx
            a = alpha_quiet + (alpha_active - alpha_quiet) * f
            xi = x[ch, i]
            yi = xi - xp + a * yp
            # Only remove the fraction that is *not* explained by active
            # excitation. Where f is high, keep whole sample (impact).
            w = np.float32(1.0) - f

            out[ch, i] = xi * (np.float32(1.0) - w) + yi * w
            xp = xi
            yp = yi
    return out


@register_processor("force_modal_dc_blocker", track_group=MODAL_DISPLACEMENT)
class ForceModalDCBlocker(BaseProcessor):
    """
    Remove the envelope-shaped DC offset of modal displacement tracks.

    The ForceDataSequence is used as the *reference* for the time-scale of
    the DC component rather than for its amplitude: modal resonators smear
    the force through a leaky integrator whose time-constant equals the
    mean T60. Any slowly-varying component of x whose shape resembles that
    integrator is removed; anything sharper (real transients) is kept.

    Params
    ------
    alpha_quiet        : float, default 0.999     # tightest cutoff
    alpha_active_active       : float, default 0.99995   # loosest at peaks
    reference_tau_ms   : float, default 20.0      # DC time constant; if the
                                                 # object config exposes a
                                                                                                 # mean_t60, that wins.
    attr               : str,   default "normal_force_magnitude"
    sample_rate        : int,   default 48000
    sfps               : float, default 24.0
    use_object_tau     : bool,  default True      # use mean_t60 if present
    """

    required_side = {"force"}

    def __init__(self, alpha_quiet: float = 0.999, alpha_active: float = 0.99995, reference_tau_ms: float = 20.0, attr: str = "normal_force_magnitude", sample_rate: int = 48000, sfps: float = 24.0, use_object_tau: bool = True, **kw):
        super().__init__(alpha_quiet=alpha_quiet, alpha_active=alpha_active, reference_tau_ms=reference_tau_ms, attr=attr, sample_rate=sample_rate, sfps=sfps, use_object_tau=use_object_tau, **kw)

    # ------------------------------------------------------------------
    def _process(self, x: np.ndarray, props) -> np.ndarray:
        seq = get_force_sequence(props)
        if seq is None:
            return x

        S = x.shape[1]
        sr = int(self.p(props, "sample_rate", self.params["sample_rate"]))
        sfps = float(self.p(props, "sfps", self.params["sfps"]))
        attr = self.p(props, "attr", self.params["attr"])
        use_obj = bool(self.p(props, "use_object_tau", self.params["use_object_tau"]))
        aq = np.float32(self.p(props, "alpha_quiet", self.params["alpha_quiet"]))
        aa = np.float32(self.p(props, "alpha_active", self.params["alpha_active"]))
        tau_ms = float(self.p(props, "reference_tau_ms", self.params["reference_tau_ms"]))

        # Object config may carry a mean_t60 (patched in _get_props).
        if use_obj and props is not None:
            cfg_obj = (props.custom or {}).get("obj_config")
            if cfg_obj is not None:
                mean_t60 = getattr(cfg_obj, "mean_t60", None)
                if mean_t60 is not None and mean_t60 > 0.0:
                    tau_ms = float(mean_t60) * 1000.0

        env = sample_envelope(seq, num_samples=S, sfps=sfps, sample_rate=sr, attr=attr, normalize=True, clip_positive=True)

        tau_samples = np.float32(max(1.0, tau_ms * sr / 1000.0))
        dc_expect = _leaky_integrate_1d(env, tau_samples)

        return _modal_dc_block_2d(x, dc_expect, aq, aa)
